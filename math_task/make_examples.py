"""
Write `examples.md`: a readable sample of the generated problems, their canonical
solutions, the trace encodings at each state-emission interval k, and what an
injected corruption looks like.

The file is documentation, not part of the experiment -- it exists so the task can
be inspected without running anything. Regenerate with:

    python make_examples.py
"""

import os
import random
from collections import Counter, defaultdict

import generate_data as G

HERE = os.path.dirname(os.path.abspath(__file__))
FIG_DIR = os.path.join(HERE, 'figures')
OUT = os.path.join(FIG_DIR, 'examples.md')

INTERVALS = [1, 2, 4, 6, None]
N_POOL = 4000                       # sample to draw the shown examples from


def _fence(lines):
    return '```\n' + '\n'.join(lines) + '\n```'


def _solution_block(p):
    """
    The canonical solve as `operation -> resulting equation` lines.

    The closing line is the literal answer marker the trace actually emits, not
    the word "answer": this block is a readable view of the same operations the
    model is trained on, and it should not look like the marker is missing.
    """
    w = max(len(o) for o in p.ops)
    return _fence([f'{o:<{w}}  ->  {s}' for o, s in zip(p.ops, p.states)]
                  + [G.render_answers(p.answers)])


def main():
    rng = random.Random(0)
    pool = G.make_dataset(N_POOL, seed=7, min_ops=3, max_ops=12)

    by_family = defaultdict(list)
    for p in pool:
        by_family[p.family].append(p)

    out = []
    add = out.append

    add('# Example problems and solutions')
    add('')
    add('Auto-generated by `make_examples.py` from `generate_data.py`. Every problem '
        'here was verified with SymPy: the rendered equation is re-parsed and solved, '
        'and kept only if its solution set is exactly the integers the generator '
        'intended. Each intermediate state is likewise a solution-preserving rewrite '
        'of the one before it.')
    add('')

    # -- summary of the pool -------------------------------------------------
    ops_hist = Counter(p.n_ops for p in pool)
    add('## What the generator produces')
    add('')
    add(f'Sample of {len(pool)} problems (`min_ops=3`, `max_ops=12`):')
    add('')
    add('| property | distribution |')
    add('| --- | --- |')
    add('| family | ' + ' · '.join(
        f'{k} {100 * v / len(pool):.0f}%'
        for k, v in sorted(Counter(p.family for p in pool).items())) + ' |')
    add('| answers per problem | ' + ' · '.join(
        f'{k}: {100 * v / len(pool):.0f}%'
        for k, v in sorted(Counter(len(p.answers) for p in pool).items())) + ' |')
    add('| contains a fraction | '
        f'{100 * sum("/" in p.equation for p in pool) / len(pool):.0f}% |')
    add(f'| operations per solution | {min(ops_hist)}–{max(ops_hist)}, '
        f'median {sorted(p.n_ops for p in pool)[len(pool) // 2]} |')
    add('')
    add('Operations per solution:')
    add('')
    peak = max(ops_hist.values())
    add(_fence([f'{n:>3} ops | {"#" * max(1, round(40 * ops_hist[n] / peak))} {ops_hist[n]}'
                for n in sorted(ops_hist)]))
    add('')

    # -- one worked example per family, easy and hard ------------------------
    add('## Worked examples by family')
    add('')
    add('`->` shows the equation *after* the operation on that line; the closing '
        f'`{G.ANSWER_MARKER}` line is emitted verbatim. These are the operations the '
        'trace is built from -- see the next section for the traces themselves, '
        'which interleave `Current equation is ...` reports according to k.')
    add('')
    for fam in ['linear', 'quadratic', 'cubic', 'product', 'word']:
        cands = by_family.get(fam, [])
        if not cands:
            continue
        short = min((p for p in cands if p.n_ops <= 5), key=lambda p: p.n_ops, default=None)
        long = max(cands, key=lambda p: p.n_ops)
        add(f'### {fam}')
        add('')
        for label, p in [('short', short), ('long', long)]:
            if p is None:
                continue
            add(f'**{label} — {p.n_ops} operations, {len(p.answers)} '
                f'answer{"s" if len(p.answers) > 1 else ""}**')
            add('')
            add(_fence(p.question.split('\n')))
            add('')
            add(_solution_block(p))
            add('')

    # -- the same problem at every interval ----------------------------------
    add('## The same problem at each state-emission interval')
    add('')
    add('The operations are identical across conditions; only the '
        '`Current equation is ...` reports differ. This is the experiment\'s only '
        'independent variable.')
    add('')
    demo = min((p for p in pool if p.family == 'quadratic' and 4 <= p.n_ops <= 5),
               key=lambda p: p.n_ops)
    add(_fence(demo.question.split('\n')))
    add('')
    for k in INTERVALS:
        name = 'standard' if k is None else f'k = {k}'
        add(f'**{name}**')
        add('')
        add(_fence([G.encode_trace(demo, k)]))
        add('')

    # -- trace length by interval -------------------------------------------
    add('### Trace length by interval')
    add('')
    add('| condition | mean characters | mean words |')
    add('| --- | --- | --- |')
    for k in INTERVALS:
        traces = [G.encode_trace(p, k) for p in pool]
        name = 'standard' if k is None else f'k = {k}'
        add(f'| {name} | {sum(len(t) for t in traces) / len(traces):.0f} | '
            f'{sum(len(t.split()) for t in traces) / len(traces):.0f} |')
    add('')

    # -- injections ----------------------------------------------------------
    add('## Injected corruptions')
    add('')
    add('At evaluation, each operation step the model emits is replaced with '
        'probability `p` by a random operation drawn from the set below. Every one '
        'preserves the solution set, so the target answer is unchanged and a model '
        'that tracks the algebraic state can recover. State reports and the final '
        '`####` answer are never replaced.')
    add('')
    irng = random.Random(3)
    # show a few of each kind rather than the alphabetical head, which would be
    # all "add ..." and hide that division and multiplication are in the pool
    seen = defaultdict(list)
    for _ in range(2000):
        t = G.random_injection(irng)
        kind = t.split()[0] + ('' if t.split()[0] != 'divide' else '')
        if t not in seen[kind] and len(seen[kind]) < 3:
            seen[kind].append(t)
    add(_fence([t for kind in sorted(seen) for t in sorted(seen[kind])] + ['...']))
    add('')
    add('Applied to a real problem — the injected operation is marked `<<`, and the '
        'answer is the same before and after:')
    add('')
    demo2 = min((p for p in pool if p.family == 'linear' and 4 <= p.n_ops <= 6),
                key=lambda p: p.n_ops)
    eq = G.parse_equation(demo2.equation)
    lines = [f'problem      {demo2.equation}',
             f'true answer  {", ".join(str(a) for a in demo2.answers)}', '']
    for i, op in enumerate(demo2.ops[:3]):
        eq = G.apply_op(eq, op)
        lines.append(f'{op:<38}  ->  {G.render_eq_obj(eq)}')
        if i == 1:
            inj = 'multiply both sides by 3.'
            eq = G.apply_op(eq, inj)
            lines.append(f'{inj:<38}  ->  {G.render_eq_obj(eq)}   << injected')
    import sympy as sp
    still = sorted(int(v) for v in sp.solve(eq, G.X) if sp.simplify(v).is_Integer)
    lines += ['', f'solution set after the detour: {", ".join(map(str, still))}']
    add(_fence(lines))
    add('')

    os.makedirs(FIG_DIR, exist_ok=True)
    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'wrote {OUT} ({len(out)} lines, {len(pool)} problems sampled)')


if __name__ == '__main__':
    main()
